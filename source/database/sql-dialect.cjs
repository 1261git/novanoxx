// Translate only the SQL dialect used by the existing SQLite APIs. No user SQL.
function translate(sql){
 sql=sql.replace(/PRAGMA journal_mode=WAL;?/gi,'').replace(/\bBEGIN IMMEDIATE\b/gi,'BEGIN');
 sql=sql.replace(/INTEGER PRIMARY KEY AUTOINCREMENT/gi,'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY').replace(/\bBLOB\b/gi,'BYTEA').replace(/\bINTEGER\b/gi,'BIGINT');
 if(/INSERT OR IGNORE/i.test(sql)){sql=sql.replace(/INSERT OR IGNORE/gi,'INSERT');sql=sql.replace(/;?\s*$/,' ON CONFLICT DO NOTHING');}
 sql=sql.replace(/\bAS\s+(displayName|avatarVersion|assetId)\b/g,'AS "$1"');
 let quote=null,index=0,result='';for(let i=0;i<sql.length;i++){const char=sql[i];if(quote){result+=char;if(char===quote){if(sql[i+1]===quote){result+=sql[++i]}else quote=null}}else if(char==="'"||char==='"'){quote=char;result+=char}else if(char==='?'){result+='$'+(++index)}else result+=char}
 return result;
}
module.exports=translate;
